"""Builds data/chronicle_items.tsv, the items the Chronicle tracks, from the game's excel tables and
English strings.

usage: py -I tools/gen_chronicle_items.py <dir from extract_d2r.py> [data/chronicle_items.tsv]

An item is tracked unless its row has disableChronicle set (or, for runewords, isn't complete);
quest uniques are left out too. Chronicle rows are the *ID column of uniqueitems.txt /
setitems.txt, and for runewords the data line index of runes.txt plus 27.
"""
import csv, json, os, sys

X = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else 'data/chronicle_items.tsv'
RUNEWORD_ROW_OFFSET = 27

# itemtypes.txt names that read differently from the Chronicle's own category names.
TYPE_LABELS = {
    'tors': 'Body Armor', 'knif': 'Dagger', 'orb': 'Sorceress Orb', 'head': 'Voodoo Head',
    'ashd': 'Auric Shield', 'phlm': 'Barbarian Helm', 'pelt': 'Druid Pelt', 'h2h': 'Claw',
    'h2h2': 'Claw', 'scha': 'Small Charm', 'mcha': 'Large Charm', 'lcha': 'Grand Charm',
}
ELEMENTS = {'ltng': 'Lightning', 'cold': 'Cold', 'fire': 'Fire', 'pois': 'Poison'}
TRIGGERS = {'death-skill': 'Death', 'levelup-skill': 'Level-up'}


def table(name):
    with open(os.path.join(X, name + '.txt'), encoding='latin1', newline='') as f:
        rows = list(csv.DictReader(f, delimiter='\t'))
    return [{k: v.strip() if isinstance(v, str) else v for k, v in r.items()} for r in rows]


STR = {}
for name in ['item-names', 'item-runes']:
    with open(os.path.join(X, name + '.json'), encoding='utf-8-sig') as f:
        for e in json.load(f):
            STR.setdefault(e['Key'], e['enUS'])


def s(key):
    return STR.get(key, key)


ITYPES = {r['Code']: r for r in table('itemtypes') if r['Code']}
BASES = {r['code']: r for t in ['weapons', 'armor', 'misc'] for r in table(t) if r.get('code')}


def base_fields(code):
    """(base name, tier, item type) of a base item code."""
    b = BASES[code]
    tiers = {b.get('normcode'): 'Normal', b.get('ubercode'): 'Exceptional', b.get('ultracode'): 'Elite'}
    tier = tiers.get(code, '') if b.get('normcode') else ''
    t = b['type']
    return s(b['namestr']), tier, TYPE_LABELS.get(t, ITYPES[t]['ItemType'])


def props(r):
    return [r.get(f'prop{i}', '') for i in range(1, 13)]


def unique_name(r):
    """The game calls all eight Rainbow Facets "Rainbow Facet"; tell them apart by element and trigger."""
    name = s(r['index'])
    if name == 'Rainbow Facet':
        ps = props(r)
        element = next(ELEMENTS[p[6:]] for p in ps if p.startswith('extra-'))
        trigger = next(TRIGGERS[p] for p in ps if p in TRIGGERS)
        name += f': {element} {trigger}'
    return name


def tracked(r):
    return r['*ID'] and r['index'] and r.get('disableChronicle') != '1'


lines = []
for r in table('setitems'):
    if tracked(r):
        base, tier, itype = base_fields(r['item'])
        lines.append(('set', int(r['*ID']), s(r['index']), base, s(r['set']), tier, itype, '', r['lvl']))
for r in table('uniqueitems'):
    if tracked(r) and not int(BASES[r['code']].get('quest') or 0):
        base, tier, itype = base_fields(r['code'])
        lines.append(('unique', int(r['*ID']), unique_name(r), base, '', tier, itype, '', r['lvl']))
for i, r in enumerate(table('runes')):
    if r['complete'] == '1':
        runes = [s(BASES[r[f'Rune{n}']]['namestr']).removesuffix(' Rune') for n in range(1, 7) if r[f'Rune{n}']]
        lines.append(('runeword', i + RUNEWORD_ROW_OFFSET, s(r['Name']), '', '', '', 'Runeword', ' '.join(runes), ''))

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Chronicle items, generated by tools/gen_chronicle_items.py from the game\'s own tables.\n')
    f.write('# rows: setitems.txt / uniqueitems.txt *ID, or runes.txt data line index + 27 for runewords.\n')
    f.write('# The eight Rainbow Facets, all "Rainbow Facet" in game, are named by element and trigger.\n')
    f.write('# kind\trows\tname\tbase\tset\ttier\ttype\trunes\tqlvl\n')
    for line in lines:
        f.write('\t'.join(map(str, line)) + '\n')
print(f'{OUT}: {len(lines)} items')
